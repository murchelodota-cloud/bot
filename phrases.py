def say(_style: str, key: str, **kw) -> str:
    bank = PHRASES.get(_style) or PHRASES["pickme"]
    variants = bank.get(key) or PHRASES["pickme"].get(key) or ["{key}"]
    text = random.choice(variants)
    try:
        return text.format(**kw)
    except KeyError:
        return text
