    custom = CUSTOM.get(chat_id, {}).get(key) if chat_id is not None else None
    if custom:
        variants = custom
    else:
        bank = PHRASES.get(_style) or PHRASES["pickme"]
        variants = bank.get(key) or PHRASES["pickme"].get(key) or ["{key}"]
    text = random.choice(variants)
    try:
        return text.format(**kw)
    except (KeyError, IndexError, ValueError):
        return text
