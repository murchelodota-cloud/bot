_last_quote: dict[int, float] = {}
_last_msg: dict[int, float] = {}


def random_quote():
    return random.choice(QUOTES)


async def send_quote(bot_or_msg, chat_id: int, via_msg: Message | None = None):
    q, a = random_quote()
    st = await style(chat_id)
    text = say(st, "quote", chat_id=chat_id, quote=q, author=a)
    if via_msg:
        sent = await via_msg.answer(text)
    else:
        sent = await bot_or_msg.send_message(chat_id, text)
    await db.remember_bot_message(chat_id, sent.message_id)
    _last_quote[chat_id] = time.time()


@router.message(Command("поумничай", "цитата", "умничай", "quote", "мудрость", prefix="!+/"))
async def cmd_quote(msg: Message):
    await send_quote(msg, msg.chat.id, via_msg=msg)


def note_activity(chat_id: int):
    _last_msg[chat_id] = time.time()


async def quote_tick(bot: Bot):
    """Раз в минуту: если включено, прошло quotes_every минут и в чате писали за последние 30 минут — цитата."""
    now = time.time()
    for chat_id in await db.all_chats():
        s = await db.settings(chat_id)
        every = int(s.get("quotes_every", 0) or 0)
        if every <= 0:
            continue
        if now - _last_quote.get(chat_id, 0) < every * 60:
            continue
        if now - _last_msg.get(chat_id, 0) > 1800:
            continue
        try:
            await send_quote(bot, chat_id)
        except Exception:
            pass
